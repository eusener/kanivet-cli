// Package shellinit gera o arquivo de init do shell com aliases, variáveis e hooks dos itens.
package shellinit

import (
	"fmt"
	"sort"
	"strings"

	"github.com/eusener/kanivet-cli/internal/catalog"
)

const header = `# Generated by kanivet-cli. Do not edit: this file is rewritten on every run.
# Gerado pelo kanivet-cli. Não edite: este arquivo é reescrito a cada execução.
`

const bootstrap = `
# Homebrew e ~/.local/bin no PATH
if ! command -v brew >/dev/null 2>&1; then
  for _kv_brew in /opt/homebrew/bin/brew /usr/local/bin/brew /home/linuxbrew/.linuxbrew/bin/brew; do
    if [ -x "$_kv_brew" ]; then
      eval "$("$_kv_brew" shellenv)"
      break
    fi
  done
  unset _kv_brew
fi
case ":$PATH:" in
  *":$HOME/.local/bin:"*) ;;
  *) export PATH="$HOME/.local/bin:$PATH" ;;
esac
`

// Generate monta o init para shell ("zsh" | "bash") com os itens informados.
func Generate(items []*catalog.Item, shell string) string {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString(bootstrap)

	var selected []*catalog.Item
	for _, it := range items {
		if it.ZshOnly && shell != "zsh" {
			continue
		}
		selected = append(selected, it)
	}
	sort.SliceStable(selected, func(i, j int) bool {
		if selected[i].Shell.InitOrder != selected[j].Shell.InitOrder {
			return selected[i].Shell.InitOrder < selected[j].Shell.InitOrder
		}
		return selected[i].ID < selected[j].ID
	})

	env := map[string]string{}
	for _, it := range selected {
		for k, v := range it.Env {
			env[k] = v
		}
		for k, v := range it.Shell.Env {
			env[k] = v
		}
	}
	if len(env) > 0 {
		b.WriteString("\n")
		for _, k := range sortedKeys(env) {
			fmt.Fprintf(&b, "export %s=%s\n", k, quote(env[k]))
		}
	}

	for _, it := range selected {
		body := initFor(it, shell)
		for _, k := range sortedKeys(it.Shell.Aliases) {
			body = append(body, fmt.Sprintf("alias %s=%s", k, quote(it.Shell.Aliases[k])))
		}
		if len(body) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\n# %s\nif command -v %s >/dev/null 2>&1; then\n", it.ID, guardBinary(it))
		for _, line := range strings.Split(strings.Join(body, "\n"), "\n") {
			if line == "" {
				b.WriteString("\n")
				continue
			}
			b.WriteString("  " + line + "\n")
		}
		b.WriteString("fi\n")
	}
	return b.String()
}

func initFor(it *catalog.Item, shell string) []string {
	if s, ok := it.Shell.Init[shell]; ok {
		return []string{strings.TrimRight(s, "\n")}
	}
	if s, ok := it.Shell.Init["any"]; ok {
		return []string{strings.TrimRight(strings.ReplaceAll(s, "{{shell}}", shell), "\n")}
	}
	return nil
}

func guardBinary(it *catalog.Item) string {
	if it.Shell.Guard != "" {
		return it.Shell.Guard
	}
	if f := strings.Fields(it.Detect.Command); len(f) > 0 {
		return f[0]
	}
	return it.ID
}

func quote(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }

func sortedKeys(m map[string]string) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
